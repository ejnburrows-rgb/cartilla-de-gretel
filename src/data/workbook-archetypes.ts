/**
 * Returns the archetype mapping for a specific printed page number (1–90).
 */
export function archetypeMappingForPage(page: number): WorkbookPageArchetypeMapping {
  if (!Number.isInteger(page) || page < 1 || page > WORKBOOK_PAGE_ARCHETYPES.length) {
    throw new RangeError(`Page out of range: ${page}`);
  }
  return WORKBOOK_PAGE_ARCHETYPES[page - 1];
}

/**
 * Returns all page mappings matching a given archetype.
 */
export function pagesForArchetype(archetype: WorkbookArchetype): readonly WorkbookPageArchetypeMapping[] {
  return WORKBOOK_PAGE_ARCHETYPES.filter((p) => p.archetypes.includes(archetype));
}
