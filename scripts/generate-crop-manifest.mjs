#!/usr/bin/env node
/**
 * scripts/generate-crop-manifest.mjs
 *
 * Generates scripts/crop-manifest.json for crop-illustrations.mjs from
 * data we already have verified: public/cartilla/art/faithful/manifest.json
 * entries that carry both `cropBox` and `sourceFlipchartPage`. This makes
 * every already-shipped crop mechanically reproducible from the raw scan —
 * no re-guessing coordinates.
 *
 * Entries in manifest.json missing `cropBox` or `sourceFlipchartPage` (crop
 * provenance was never recorded, usually because the crop was made by hand
 * before this tooling existed) cannot be regenerated. They are listed in
 * OPERATOR-NEEDS.md instead of guessing a box.
 *
 * Usage:
 *   node scripts/generate-crop-manifest.mjs
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");

const manifestJsonPath = path.join(rootDir, "public/cartilla/art/faithful/manifest.json");
const sourceRoot = path.join(rootDir, "public/cartilla/images/source");
const cropManifestOut = path.join(__dirname, "crop-manifest.json");
const operatorNeedsOut = path.join(rootDir, "OPERATOR-NEEDS.md");

/** Build filename -> full path index across every letter subfolder under public/cartilla/images/source. */
function indexSourceFiles() {
  const index = new Map();
  for (const entry of fs.readdirSync(sourceRoot, { withFileTypes: true })) {
    const full = path.join(sourceRoot, entry.name);
    if (entry.isDirectory()) {
      for (const f of fs.readdirSync(full)) {
        if (!index.has(f)) index.set(f, path.join(full, f));
      }
    } else {
      if (!index.has(entry.name)) index.set(entry.name, full);
    }
  }
  return index;
}

function main() {
  const artManifest = JSON.parse(fs.readFileSync(manifestJsonPath, "utf8"));
  const fileIndex = indexSourceFiles();

  const cropManifest = [];
  const needsOperator = [];

  for (const entry of artManifest) {
    const { slug, cropBox, sourceFlipchartPage, src } = entry;
    if (!cropBox || !sourceFlipchartPage) {
      needsOperator.push({
        slug,
        reason:
          "no cropBox/sourceFlipchartPage recorded in manifest.json — was cropped by hand before this tooling existed",
      });
      continue;
    }
    const sourceFull = fileIndex.get(sourceFlipchartPage);
    if (!sourceFull) {
      needsOperator.push({
        slug,
        reason: `sourceFlipchartPage "${sourceFlipchartPage}" not found under public/cartilla/images/source/**`,
      });
      continue;
    }
    const [x, y, width, height] = cropBox;
    cropManifest.push({
      slug,
      source: path.relative(rootDir, sourceFull),
      x,
      y,
      width,
      height,
      output: `public/cartilla/art/extracted/${slug}.webp`,
    });
  }

  fs.writeFileSync(cropManifestOut, JSON.stringify(cropManifest, null, 2) + "\n");
  console.log(
    `✓ wrote ${cropManifest.length} entries → ${path.relative(rootDir, cropManifestOut)}`,
  );

  if (needsOperator.length > 0) {
    const body = [
      "# OPERATOR-NEEDS.md",
      "",
      "Auto-generated by scripts/generate-crop-manifest.mjs — items here have no",
      "recorded crop provenance (source scan + pixel box), so the crop tool",
      "cannot reproduce them mechanically. Nothing was guessed.",
      "",
      ...needsOperator.map((n) => `- **${n.slug}** — ${n.reason}`),
      "",
    ].join("\n");
    fs.writeFileSync(operatorNeedsOut, body);
    console.log(
      `✓ wrote ${needsOperator.length} unresolvable entries → ${path.relative(rootDir, operatorNeedsOut)}`,
    );
  } else if (fs.existsSync(operatorNeedsOut)) {
    fs.rmSync(operatorNeedsOut);
  }
}

main();
